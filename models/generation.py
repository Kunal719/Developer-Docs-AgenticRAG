from pydantic import BaseModel
from models.retrieval_plan import MetadataFilters

class RetrievalGap(BaseModel):
    """
    A single piece of missing evidence identified by LLM

    suggested_query/suggested_filters feed a single direct hybrid
    retrieval pass in the gap-round loop. The gap loop does NOT re-invoke
    query_router.py, it reuses this suggestion directly, to keep each
    round cheap.
    """
    missing_topic: str
    suggested_query: str
    suggested_filters: MetadataFilters | None = None

class GeneratedAnswer(BaseModel):
    """
    Structure for the answer generated by the LLM
    """
    answer: str
    gaps: list[RetrievalGap]
    is_complete: bool

class NormalizedInput(BaseModel):
    """
    Output of pipeline/input_normalizer.py.
 
    Same field shape as QueryInput — this effectively *is* a QueryInput,
    just constructed by an LLM call from raw text instead of being mapped
    from BenchmarkQuestion via to_query_input().
 
    Must NOT hallucinate observed_behavior / expected_behavior when the
    raw input has nothing to extract (e.g. a simple "what does X do?"
    question) — pass through as close to identity as possible in that
    case. Guard this with a few-shot "nothing to extract" example in
    prompt/router_prompt.py's normalizer prompt.
    """
 
    question: str
    code_snippet: str | None = None
    error: str | None = None
    logs: str | None = None
    observed_behavior: str | None = None
    expected_behavior: str | None = None
 